    function lookup(core) {
        if (Object.prototype.hasOwnProperty.call(DE, core)) return DE[core];
        // "Label:" / "Label…" / "Label..." variants of a known label
        const m = core.match(/^(.*?)(\s*(?::|…|\.\.\.))$/);
        if (m && Object.prototype.hasOwnProperty.call(DE, m[1])) return DE[m[1]] + m[2];
        for (const [re, rep] of PATTERNS) {
            if (re.test(core)) return core.replace(re, rep);
        }
        return null;
    }

    function translateString(s) {
        if (!s || !/[A-Za-z]/.test(s)) return null;
        const m = s.match(/^(\s*)([\s\S]*?)(\s*)$/);
        const core = m[2].replace(/\s+/g, ' ');
        const t = lookup(core);
        return t === null || t === core ? null : m[1] + t + m[3];
    }

    function skipped(el) {
        for (let n = el; n && n.nodeType === 1; n = n.parentElement) {
            if (SKIP_TAGS.has(n.tagName) || n.hasAttribute('data-no-i18n') || n.isContentEditable) return true;
        }
        return false;
    }

    function translateElementAttrs(el) {
        for (const a of ATTRS) {
            const v = el.getAttribute(a);
            if (v) {
                const t = translateString(v);
                if (t !== null) el.setAttribute(a, t);
            }
        }
        if (el.tagName === 'INPUT' && (el.type === 'button' || el.type === 'submit') && el.value) {
            const t = translateString(el.value);
            if (t !== null) el.value = t;
        }
    }

